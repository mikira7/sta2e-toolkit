const size = 64, alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const clamp = v => Math.max(0, Math.min(1, v));
const smooth = (a, b, x) => { const t = clamp((x - a) / (b - a)); return t * t * (3 - 2 * t); };
const hash = (x, y, seed) => { let n = Math.imul(x + seed * 137, 374761393) ^ Math.imul(y + 47, 668265263); n = Math.imul(n ^ n >>> 13, 1274126177); return (n ^ n >>> 16) >>> 0; };
function noise(x, y, cells, seed) {
  x *= cells; y *= cells;
  const ix = Math.floor(x), iy = Math.floor(y), tx = smooth(0, 1, x - ix), ty = smooth(0, 1, y - iy);
  const at = (a, b) => hash((a % cells + cells) % cells, (b % cells + cells) % cells, seed) / 4294967295;
  const a = at(ix, iy) * (1 - tx) + at(ix + 1, iy) * tx;
  const b = at(ix, iy + 1) * (1 - tx) + at(ix + 1, iy + 1) * tx;
  return a * (1 - ty) + b * ty;
}
const maps = [];
for (let variant = 0; variant < 3; variant++) {
  let heights = Float64Array.from({ length: size * size }, (_, i) => {
    const x = i % size / size, y = Math.floor(i / size) / size;
    const bend = (noise(x, y, 4, variant + 17) - .5) * .16;
    const ridge = 1 - Math.abs(noise(x + bend, y - bend, 8, variant + 91) * 2 - 1);
    return ridge * .55 + noise(x, y, 16, variant + 33) * .3 + noise(x, y, 32, variant + 73) * .15;
  });
  // Thermal weathering softens slopes and settles material into local hollows.
  for (let pass = 0; pass < 18; pass++) {
    const next = heights.slice();
    for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
      const i = y * size + x;
      for (const [dx, dy] of [[1, 0], [0, 1]]) {
        const j = ((y + dy) % size) * size + (x + dx) % size;
        const difference = heights[i] - heights[j];
        const transfer = Math.sign(difference) * Math.max(0, Math.abs(difference) - .025) * .18;
        next[i] -= transfer; next[j] += transfer;
      }
    }
    heights = next;
  }
  maps.push({ name: `rock-${variant}`, values: Array.from(heights) });
}
for (let variant = 0; variant < 4; variant++) {
  maps.push({ name: `impact-${variant}`, values: Array.from({ length: size * size }, (_, i) => {
    const u = (i % size / (size - 1) * 2 - 1) * 1.4, v = (Math.floor(i / size) / (size - 1) * 2 - 1) * 1.4;
    const r = Math.hypot(u, v), angle = Math.atan2(v, u);
    const wall = smooth(.35, .60, r) * (1 - smooth(1.05, 1.35, r));
    const broken = noise(u * .35 + .5, v * .35 + .5, 16, variant + 111) - .5;
    const terraces = Math.sin(r * (32 + variant * 5) + Math.sin(angle * 5 + variant) * 1.8 + broken * 3) * (.4 + noise(u * .2 + .5, v * .2 + .5, 8, variant + 217) * .6);
    const gullies = Math.sin(angle * (19 + variant * 4) + r * 5 + variant);
    return .5 + wall * (terraces * .18 + gullies * .12 + broken * .30);
  }) });
}
const encoded = maps.map(m => m.values.map(v => alphabet[Math.round(clamp(v) * 63)]).join(""));
await writeFile(new URL("../scripts/barren-texture-data.js", import.meta.url), `/** Baked height maps. Generated by tools/bake-barren-textures.mjs; do not hand-edit. */\nexport const BARREN_MAP_SIZE = ${size};\nexport const BARREN_MAP_NAMES = ${JSON.stringify(maps.map(m => m.name))};\nexport const BARREN_MAPS = ${JSON.stringify(encoded, null, 2)}.map(text => Float32Array.from(text, c => "${alphabet}".indexOf(c) / 63));\n`);
// Grayscale proof of the exact data shipped to the renderer.
const width = size * maps.length, height = size, bytes = Buffer.alloc((width * 4 + 1) * height);
for (let k = 0; k < maps.length; k++) for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
  const i = y * (width * 4 + 1) + 1 + (k * size + x) * 4;
  const value = Math.round(alphabet.indexOf(encoded[k][y * size + x]) / 63 * 255);
  bytes[i] = bytes[i + 1] = bytes[i + 2] = value; bytes[i + 3] = 255;
}
function chunk(type, data) {
  const name = Buffer.from(type), length = Buffer.alloc(4), checksum = Buffer.alloc(4); let crc = -1;
  for (const b of Buffer.concat([name, data])) { crc ^= b; for (let i = 0; i < 8; i++) crc = crc >>> 1 ^ (0xedb88320 & -(crc & 1)); }
  length.writeUInt32BE(data.length); checksum.writeUInt32BE((crc ^ -1) >>> 0);
  return Buffer.concat([length, name, data, checksum]);
}
